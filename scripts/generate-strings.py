#!/usr/bin/env python3
"""Generate typed Swift accessors from String Catalog keys and arguments."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Bundle/Localizable.xcstrings"
OUTPUT = ROOT / "Sources/Tenmaku/Strings.swift"
FORMAT = re.compile(r"%%|%@|%lld")


def parameters(value):
    if "%" in FORMAT.sub("", value):
        raise ValueError(f"Unsupported format specifier: {value}")
    return [part for part in FORMAT.findall(value) if part != "%%"]


def units(localization):
    if "stringUnit" in localization:
        yield localization["stringUnit"]
    for variants in localization.get("variations", {}).values():
        for variant in variants.values():
            yield from units(variant)


def generate():
    catalog = json.loads(CATALOG.read_text())
    assert catalog["sourceLanguage"] == "en", "The source language must be English"
    lines = ["// Generated by scripts/generate-strings.py. Edit copy in Bundle/Localizable.xcstrings.", "import Foundation", "", "enum L10n {"]
    symbols = set()
    for key, entry in sorted(catalog["strings"].items()):
        assert re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", key), key
        parts = re.split(r"[._]", key)
        symbol = parts[0] + ''.join(part.capitalize() for part in parts[1:])
        assert symbol not in symbols, f"Duplicate symbol: {symbol}"
        symbols.add(symbol)
        localization = entry["localizations"][catalog["sourceLanguage"]]
        source_unit = localization.get("stringUnit") or localization["variations"]["plural"]["other"]["stringUnit"]
        source = source_unit["value"]
        args = parameters(source)
        for language in ("ja", "en"):
            translations = list(units(entry["localizations"][language]))
            assert translations, f"Missing translation: {key}/{language}"
            for unit in translations:
                assert unit["state"] == "translated" and unit["value"], f"Untranslated: {key}/{language}"
                assert parameters(unit["value"]) == args, f"Format arguments do not match: {key}/{language}"
        signature = [f"_ arg{i}: {'Int' if spec == '%lld' else 'String'}" for i, spec in enumerate(args, 1)]
        signature += ["bundle: Bundle = .main", "locale: Locale = .current"]
        lookup = f'bundle.localizedString(forKey: "{key}", value: nil, table: nil)'
        arguments = ', '.join(f"arg{i}" for i in range(1, len(args) + 1))
        lines += [f"    static func {symbol}({', '.join(signature)}) -> String {{",
                  f"        String(format: {lookup}, locale: locale, arguments: [{arguments}])",
                  "    }", ""]
    lines += ["}", ""]
    return '\n'.join(lines), len(symbols)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check translations and generated files without writing changes")
    args = parser.parse_args()
    generated, count = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            sys.exit("Strings.swift is missing or out of date. Run python3 scripts/generate-strings.py.")
    else:
        OUTPUT.write_text(generated)
    print(f"{count} entries: English and Japanese translations, format arguments, and Swift accessors passed")


if __name__ == "__main__":
    main()
